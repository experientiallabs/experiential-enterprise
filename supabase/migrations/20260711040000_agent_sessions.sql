-- Org members read their sessions; the service role (API + driver) writes.
create policy agent_sessions_select_member
  on public.agent_sessions
  for select
  to authenticated
  using (org_id in (select public.member_org_ids()));

-- Events reach their organization through the session (like agent_opt_runs
-- through agents). Members read; only the service role appends.
create policy agent_session_events_select_member
  on public.agent_session_events
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.agent_sessions sessions
      where sessions.id = agent_session_events.session_id
        and sessions.org_id in (select public.member_org_ids())
    )
  );

